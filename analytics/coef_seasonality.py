def calculate_seasonality(data):
    '''
    На вход подается словарь словарей вида: {Год: {Месяц: Доход}}
    пример: {2024: {Январь: 55000, …, Декабрь: 65000}, 2025: {Январь: 70000, …, Декабрь: 80000}}

    1) Нахождение среднего значения месяца по истории: Проходимся по каждому году и по каждому месяцу. Для каждого месяца находим среднее арифметическое значение показателя:
    Среднее значение месяца = Сумма значений этого месяца за все годы / Кол-во таких месяцев в истории (словаре)

    2) Нахождение базового уровня (базового среднего): Находим среднее значение среди уже рассчитанных 12 месяцев:
    Среднегодовое месячное значение = Сумма средних значений всех 12 месяцев / 12

    3) Расчет индекса сезонности:
    Индекс сезонности месяца = Среднее значение конкретного месяца / Среднегодовое месячное значение

    На выходе получаем:
    Словарь/массив из 12 коэффициентов сезонности (один на каждый месяц года):
    Индекс Января (например, 0.95)
    Индекс Февраля (например, 1.02)
    …
    Индекс Июля (например, 0.15 - сильный спад активности, каникулы)
    …
    Индекс Сентября (например, 1.20 - рост показателя, начало учебы)
    '''

    # считаем среднее значение показателя для каждого месяца за все годы
    month_sums = {}
    month_counts = {}

    for year, months in data.items():
        for month_name, value in months.items():
            if month_name not in month_sums:
                month_sums[month_name] = 0.0
                month_counts[month_name] = 0
            month_sums[month_name] += value
            month_counts[month_name] += 1

    # находим среднее арифметическое для каждого месяца
    monthly_averages = {}
    for month_name in month_sums:
        monthly_averages[month_name] = (
            month_sums[month_name] / month_counts[month_name]
        )

    # находим среднегодовое месячное значение (базу сравнения)
    total_months_sum = sum(monthly_averages.values())
    annual_monthly_average = total_months_sum / len(monthly_averages)

    # считаем индекс сезонности для каждого месяца
    seasonality_indices = {}
    for month_name, avg_value in monthly_averages.items():
        # округляем до 2 знаков после запятой
        seasonality_indices[month_name] = round(
            avg_value / annual_monthly_average, 2
        )

    return seasonality_indices


# ПРИМЕР 1: Считаем сезонность для количества новых клиентов
clients_data = {
    2024: {"Январь": 120, "Февраль": 110, "Июль": 30, "Сентябрь": 250},
    2025: {"Январь": 140, "Июль": 40, "Сентябрь": 280, "Ноябрь": 260},
}
print("Индексы для клиентов:", calculate_seasonality(clients_data))

# ПРИМЕР 2: Считаем сезонность для среднего чека
ticket_data = {
    2024: {"Январь": 1500, "Июль": 1100, "Сентябрь": 1800},
    2025: {"Январь": 1600, "Июль": 1150, "Сентябрь": 1950},
}
print("Индексы для ср. чека:", calculate_seasonality(ticket_data))
