def calculate_seasonality(data):
    '''
    На вход подается словарь словарей вида: {Год: {Номер_месяца: Доход}}
    пример: {2024: {1: 55000, …, 12: 65000}, 2025: {1: 70000, …, 12: 80000}}

    1) Нахождение среднего значения месяца по истории: Проходимся по каждому году и по каждому месяцу. Для каждого месяца находим среднее арифметическое значение показателя:
    Среднее значение месяца = Сумма значений этого месяца за все годы / Кол-во таких месяцев в истории (словаре)

    2) Нахождение базового уровня (базового среднего): Находим среднее значение среди уже рассчитанных 12 месяцев:
    Среднегодовое месячное значение = Сумма средних значений всех 12 месяцев / 12

    3) Расчет индекса сезонности:
    Индекс сезонности месяца = Среднее значение конкретного месяца / Среднегодовое месячное значение

    На выходе получаем:
    Словарь из 12 коэффициентов сезонности (один на каждый месяц года):
    Индекс месяца 1 (январь) (например, 0.95)
    Индекс месяца 2 (февраль) (например, 1.02)
    …
    Индекс месяца 7 (июль) (например, 0.15 - сильный спад активности, каникулы)
    …
    Индекс месяца 9 (сентябрь) (например, 1.20 - рост показателя, начало учебы)
    '''

    # считаем среднее значение показателя для каждого месяца за все годы
    month_sums = {}
    month_counts = {}

    for year, months in data.items():
        for month_num, value in months.items():
            if month_num not in month_sums:
                month_sums[month_num] = 0.0
                month_counts[month_num] = 0
            month_sums[month_num] += value
            month_counts[month_num] += 1

    # находим среднее арифметическое для каждого месяца
    monthly_averages = {}
    for month_num in month_sums:
        monthly_averages[month_num] = (
            month_sums[month_num] / month_counts[month_num]
        )

    # находим среднегодовое месячное значение (базу сравнения)
    total_months_sum = sum(monthly_averages.values())
    annual_monthly_average = total_months_sum / len(monthly_averages)

    # считаем индекс сезонности для каждого месяца
    seasonality_indices = {}
    for month_num, avg_value in monthly_averages.items():
        # округляем до 2 знаков после запятой
        seasonality_indices[month_num] = round(
            avg_value / annual_monthly_average, 2
        )

    return seasonality_indices


